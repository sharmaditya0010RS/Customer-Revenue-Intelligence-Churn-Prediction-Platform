/* ============================================================
   UNIFIED CUSTOMER VIEW

   Historical + permanently generated population.

   Historical customers retain known churn outcome.
   Generated customers have no known actual churn outcome.
   ============================================================ */

CREATE OR REPLACE VIEW analytics.vw_all_customers AS

SELECT
    c.customer_id,
    c.gender,
    c.senior_citizen,
    c.partner,
    c.dependents,
    c.tenure,
    c.phone_service,
    c.multiple_lines,
    c.internet_service,
    c.online_security,
    c.online_backup,
    c.device_protection,
    c.tech_support,
    c.streaming_tv,
    c.streaming_movies,
    c.contract,
    c.paperless_billing,
    c.payment_method,
    c.monthly_charges,
    c.total_charges,
    c.tenure_group,
    c.avg_revenue_per_tenure_month,
    c.service_count,

    c.churn AS actual_churn_label,
    c.churn_flag AS actual_churn,

    'Historical'::VARCHAR AS customer_source,

    NULL::TIMESTAMPTZ AS generated_at

FROM analytics.customers AS c

UNION ALL

SELECT
    c.customer_id,
    c.gender,
    c.senior_citizen,
    c.partner,
    c.dependents,
    c.tenure,
    c.phone_service,
    c.multiple_lines,
    c.internet_service,
    c.online_security,
    c.online_backup,
    c.device_protection,
    c.tech_support,
    c.streaming_tv,
    c.streaming_movies,
    c.contract,
    c.paperless_billing,
    c.payment_method,
    c.monthly_charges,
    c.total_charges,
    c.tenure_group,
    c.avg_revenue_per_tenure_month,
    c.service_count,

    NULL::VARCHAR AS actual_churn_label,
    NULL::INTEGER AS actual_churn,

    'Generated'::VARCHAR AS customer_source,

    c.generated_at

FROM analytics.live_customers AS c;


/* ============================================================
   UNIFIED ML RISK VIEW

   Historical model predictions + live predictions.
   ============================================================ */

CREATE OR REPLACE VIEW analytics.vw_all_customer_risk AS

SELECT
    c.customer_id,
    c.gender,
    c.senior_citizen,
    c.partner,
    c.dependents,
    c.tenure,
    c.tenure_group,
    c.contract,
    c.internet_service,
    c.payment_method,
    c.monthly_charges,
    c.total_charges,
    c.service_count,

    c.churn_flag AS actual_churn,

    p.churn_probability,
    p.predicted_churn,
    p.risk_segment,
    p.retention_priority,
    p.expected_monthly_revenue_at_risk,

    'Historical'::VARCHAR AS customer_source,

    NULL::TIMESTAMPTZ AS generated_at

FROM analytics.customers AS c

INNER JOIN analytics.customer_predictions AS p
    ON c.customer_id = p.customer_id

UNION ALL

SELECT
    c.customer_id,
    c.gender,
    c.senior_citizen,
    c.partner,
    c.dependents,
    c.tenure,
    c.tenure_group,
    c.contract,
    c.internet_service,
    c.payment_method,
    c.monthly_charges,
    c.total_charges,
    c.service_count,

    NULL::INTEGER AS actual_churn,

    p.churn_probability,
    p.predicted_churn,
    p.risk_segment,
    p.retention_priority,
    p.expected_monthly_revenue_at_risk,

    'Generated'::VARCHAR AS customer_source,

    c.generated_at

FROM analytics.live_customers AS c

INNER JOIN analytics.live_predictions AS p
    ON c.customer_id = p.customer_id;


/* ============================================================
   LIVE PLATFORM KPI VIEW
   ============================================================ */

CREATE OR REPLACE VIEW analytics.vw_platform_kpis AS

SELECT

    COUNT(*) AS total_customers,

    COUNT(*) FILTER (
        WHERE customer_source = 'Historical'
    ) AS historical_customers,

    COUNT(*) FILTER (
        WHERE customer_source = 'Generated'
    ) AS generated_customers,

    COUNT(*) FILTER (
        WHERE predicted_churn = 1
    ) AS predicted_churn_customers,

    COUNT(*) FILTER (
        WHERE risk_segment = 'Critical'
    ) AS critical_risk_customers,

    COUNT(*) FILTER (
        WHERE risk_segment IN (
            'High',
            'Critical'
        )
    ) AS high_critical_risk_customers,

    ROUND(
        SUM(monthly_charges::NUMERIC),
        2
    ) AS total_monthly_revenue,

    ROUND(
        SUM(
            expected_monthly_revenue_at_risk::NUMERIC
        ),
        2
    ) AS expected_monthly_revenue_at_risk,

    ROUND(
        AVG(churn_probability::NUMERIC)
        * 100,
        2
    ) AS avg_churn_probability_pct

FROM analytics.vw_all_customer_risk;