/* ============================================================
   CUSTOMER REVENUE INTELLIGENCE
   LIVE DATA GENERATION PLATFORM
   ============================================================ */

CREATE SCHEMA IF NOT EXISTS analytics;


/* ============================================================
   LIVE CUSTOMERS

   Permanently stores synthetic customers generated by the
   Streamlit command center / simulation engine.

   These rows are NOT part of the historical labeled
   training population.
   ============================================================ */

CREATE TABLE IF NOT EXISTS analytics.live_customers (

    customer_id VARCHAR(30) PRIMARY KEY,

    gender VARCHAR(20) NOT NULL,

    senior_citizen INTEGER NOT NULL
        CHECK (senior_citizen IN (0, 1)),

    partner VARCHAR(10) NOT NULL,

    dependents VARCHAR(10) NOT NULL,

    tenure INTEGER NOT NULL
        CHECK (tenure >= 0),

    phone_service VARCHAR(10) NOT NULL,

    multiple_lines VARCHAR(30) NOT NULL,

    internet_service VARCHAR(30) NOT NULL,

    online_security VARCHAR(30) NOT NULL,

    online_backup VARCHAR(30) NOT NULL,

    device_protection VARCHAR(30) NOT NULL,

    tech_support VARCHAR(30) NOT NULL,

    streaming_tv VARCHAR(30) NOT NULL,

    streaming_movies VARCHAR(30) NOT NULL,

    contract VARCHAR(30) NOT NULL,

    paperless_billing VARCHAR(10) NOT NULL,

    payment_method VARCHAR(50) NOT NULL,

    monthly_charges NUMERIC(10, 2) NOT NULL
        CHECK (monthly_charges >= 0),

    total_charges NUMERIC(12, 2) NOT NULL
        CHECK (total_charges >= 0),

    tenure_group VARCHAR(30) NOT NULL,

    avg_revenue_per_tenure_month NUMERIC(12, 4) NOT NULL
        CHECK (avg_revenue_per_tenure_month >= 0),

    service_count INTEGER NOT NULL
        CHECK (service_count >= 0),

    generated_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    source VARCHAR(30) NOT NULL
        DEFAULT 'synthetic_engine'
);


/* ============================================================
   LIVE PREDICTIONS

   One current prediction per generated customer.
   ============================================================ */

CREATE TABLE IF NOT EXISTS analytics.live_predictions (

    customer_id VARCHAR(30) PRIMARY KEY,

    churn_probability DOUBLE PRECISION NOT NULL
        CHECK (
            churn_probability >= 0
            AND churn_probability <= 1
        ),

    predicted_churn INTEGER NOT NULL
        CHECK (predicted_churn IN (0, 1)),

    risk_segment VARCHAR(20) NOT NULL,

    retention_priority VARCHAR(50) NOT NULL,

    expected_monthly_revenue_at_risk NUMERIC(12, 2)
        NOT NULL,

    model_name VARCHAR(100) NOT NULL,

    decision_threshold DOUBLE PRECISION NOT NULL,

    scored_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_live_prediction_customer
        FOREIGN KEY (customer_id)
        REFERENCES analytics.live_customers(customer_id)
        ON DELETE CASCADE
);


/* ============================================================
   GENERATION ENGINE STATE

   Single-row control table.
   PostgreSQL becomes the source of truth for engine state.
   ============================================================ */

CREATE TABLE IF NOT EXISTS analytics.generator_state (

    engine_id INTEGER PRIMARY KEY
        CHECK (engine_id = 1),

    is_running BOOLEAN NOT NULL
        DEFAULT FALSE,

    generation_interval_seconds DOUBLE PRECISION NOT NULL
        DEFAULT 2.0
        CHECK (generation_interval_seconds >= 0.5),

    generated_this_run INTEGER NOT NULL
        DEFAULT 0,

    total_generated INTEGER NOT NULL
        DEFAULT 0,

    last_customer_id VARCHAR(30),

    started_at TIMESTAMPTZ,

    stopped_at TIMESTAMPTZ,

    heartbeat_at TIMESTAMPTZ,

    updated_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP
);


INSERT INTO analytics.generator_state (
    engine_id,
    is_running,
    generation_interval_seconds,
    generated_this_run,
    total_generated
)
VALUES (
    1,
    FALSE,
    2.0,
    0,
    0
)
ON CONFLICT (engine_id) DO NOTHING;


/* ============================================================
   GENERATION LOG

   Provides permanent audit history for the command center.
   ============================================================ */

CREATE TABLE IF NOT EXISTS analytics.generation_log (

    log_id BIGSERIAL PRIMARY KEY,

    customer_id VARCHAR(30),

    event_type VARCHAR(30) NOT NULL,

    message TEXT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP
);


